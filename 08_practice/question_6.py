'''
Write a program that:

Takes two numbers as input from the user.

Prints their:

Sum
Difference
Product
Quotient

'''
a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

print("a + b is ", a + b)
print("a - b is ", a - b)
print("a * b is ", a * b)
print("a / b is ", a / b)